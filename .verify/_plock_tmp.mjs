import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const puppeteer = require("puppeteer-core");
const chromium = require("@sparticuz/chromium").default || require("@sparticuz/chromium");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await puppeteer.launch({ executablePath: await chromium.executablePath(),
  args: [...chromium.args, "--no-sandbox"], headless: true, defaultViewport: { width: 1024, height: 768 } });
const page = await browser.newPage();
await page.goto("http://127.0.0.1:8080/rooms.html", { waitUntil: "networkidle0", timeout: 120000 });
await page.waitForFunction(() => document.querySelector("[data-walk]")?.__walk?.renderer, { timeout: 30000 });
await page.evaluate(() => document.querySelectorAll("[data-walk-stop]")[5].click());
await sleep(4000);
const yaw0 = await page.evaluate(() => document.querySelector("[data-walk]").__walk.yaw);
const box = await page.evaluate(() => { const r = document.querySelector("[data-walk-view]").getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
await page.mouse.click(box.x, box.y, { clickCount: 2 });
await sleep(900);
const locked = await page.evaluate(() => !!document.pointerLockElement);
console.log("locked?", locked, "yaw", yaw0, "pitch", await page.evaluate(() => document.querySelector("[data-walk]").__walk.pitch));
await page.mouse.move(box.x + 100, box.y);
await sleep(700);
const yaw1 = await page.evaluate(() => document.querySelector("[data-walk]").__walk.yaw);
console.log("after +100px:", yaw1, "delta", (yaw1 - yaw0).toFixed(2));
await browser.close();
